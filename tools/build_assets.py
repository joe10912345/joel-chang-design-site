"""Build site/assets/css/custom.css and site/assets/js/custom.js from the pieces in src/ (Joel 2026-11-27).
   由 src/ 裡的小檔組合出網站實際載入的 custom.css 與 custom.js。

   src/css/<area>/<effect>.css and src/js/<area>/<effect>.js hold one effect each; src/css/ORDER.txt and
   src/js/ORDER.txt list them in load order (CSS: later wins, so keep related rules in this order).
   每個效果一個檔，ORDER.txt 決定合併順序（CSS 後面的優先，順序不要隨意改）。

   Usage 用法:
     python tools/build_assets.py           build both files and bump their ?v= in every page HTML
                                            組合兩個檔案並更新所有頁面的 ?v=
     python tools/build_assets.py --check   only report whether the built files are up to date 只檢查是否需要重建

   A new effect: add the file under src/, add its path to ORDER.txt, run this script. 新效果：新增檔案、加進 ORDER.txt、執行本腳本。
"""
import glob, hashlib, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
JS_HEAD = ('/* custom.js — GENERATED by tools/build_assets.py from src/js/ (one file per effect). Edit those files, then run\r\n'
           '   python tools/build_assets.py. 由 src/js/ 自動產生，請改 src/js/ 再執行 build_assets.py。 */\r\n'
           '(function () {\r\n'
           "  function ready(fn) { document.readyState === 'loading' ? document.addEventListener('DOMContentLoaded', fn) : fn(); }\r\n")
JS_TAIL = '})();\r\n'
CSS_HEAD = ('/* custom.css — GENERATED by tools/build_assets.py from src/css/ (one file per effect). Edit those files, then run\n'
            '   python tools/build_assets.py. 由 src/css/ 自動產生，請改 src/css/ 再執行 build_assets.py。 */\n')


def read(p):
    return open(p, 'rb').read().decode('utf-8')


def join(kind):
    base = os.path.join(ROOT, 'src', kind)
    order = [l.strip() for l in read(os.path.join(base, 'ORDER.txt')).splitlines() if l.strip() and not l.startswith('#')]
    listed = set(order)
    loose = [os.path.relpath(p, base).replace(os.sep, '/') for p in glob.glob(os.path.join(base, '**', '*.' + kind), recursive=True)]
    missing = [p for p in loose if p not in listed]
    if missing:
        sys.exit('Not in src/%s/ORDER.txt 沒有列在 ORDER.txt: %s' % (kind, ', '.join(missing)))
    return ''.join(read(os.path.join(base, p)) for p in order)


def build():
    return {'site/assets/css/custom.css': CSS_HEAD + join('css'),
            'site/assets/js/custom.js': JS_HEAD + join('js') + JS_TAIL}


def bump(rel, text):
    name = os.path.basename(rel)
    h = hashlib.md5(text.encode('utf-8')).hexdigest()[:8]
    for f in glob.glob(os.path.join(ROOT, 'site', '**', 'index.html'), recursive=True):
        s = read(f)
        t = re.sub(re.escape(name) + r'\?v=[0-9a-f]+', name + '?v=' + h, s)
        if t != s:
            open(f, 'wb').write(t.encode('utf-8'))


if __name__ == '__main__':
    out = build()
    stale = [rel for rel, text in out.items() if read(os.path.join(ROOT, rel)) != text]
    if '--check' in sys.argv:
        print('up to date 已是最新' if not stale else 'needs build 需要重建: ' + ', '.join(stale))
        sys.exit(1 if stale else 0)
    for rel, text in out.items():
        open(os.path.join(ROOT, rel), 'wb').write(text.encode('utf-8'))
        bump(rel, text)
    print('built 已產生:', ', '.join(out), '| changed 有變更:', ', '.join(stale) or 'none 無')
